/**
 * 弹窗层级管理（useDialogZIndex）
 *
 * ============================================================
 * 解决什么问题
 * ============================================================
 * ProtoDialog / ProtoConfirm 都 Teleport 到 <body>，而 prototype.css 里
 * `.mask` 的 z-index 是固定值 1000。于是多个弹窗同时打开时，
 * 「谁在 DOM 里靠后谁在上面」——这跟「谁后打开」完全无关，因为
 * 模板里的书写顺序是固定的。
 *
 * 实际踩到的坑（2026-10-04 用户反馈）：
 *   职位管理 → 点「＋ 新建职位」打开表单弹窗（formOpen）
 *            → 在表单里点「＋ 配置权限」打开权限树弹窗（treeOpen）
 *   但 treeOpen 在 RoleManage.vue 里的书写位置【早于】 formOpen，
 *   所以配置权限弹窗被新建职位弹窗盖住了 —— 点了像没反应。
 *
 * ============================================================
 * 解法：全局单调递增的层级序号
 * ============================================================
 * 每个弹窗「打开时」领一个比之前所有弹窗都大的序号，
 * 于是【后打开的弹窗一定在上层】，天然支持任意层嵌套，
 * 且不需要改 prototype.css 的公共样式（避免影响其它页面）。
 *
 * ⚠️ 为什么不用「栈 + 出栈」？
 *    弹窗不一定按后进先出关闭（用户可能先关下层的新建职位、再关上层的配置权限），
 *    出栈会把层级算乱。用单调递增序号则完全不依赖关闭顺序。
 */

/** 基础层级：与 prototype.css 的 .mask 原值保持一致 */
const BASE_Z = 1000;

/** 全局递增序号（模块级，所有弹窗共享） */
let seq = 0;

/**
 * 领一个新的层级值。
 * @returns 该弹窗应使用的 z-index
 */
export function acquireZIndex(): number {
  seq += 1;
  return BASE_Z + seq;
}

/**
 * 重置计数器（仅测试用；正常业务不需要调用）
 */
export function resetZIndexSeq(): void {
  seq = 0;
}
